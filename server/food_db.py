def _norm(s):
    """匹配前归一：去空白/标点/括号装饰，转小写。米饭(蒸)、 米饭。 → 米饭"""
    import re
    return re.sub(r"[\s,，。、·'’\"“”()（）\[\]【】\-—_/]+", "", str(s or "").lower())


def match_food(name):
    """食材名 → 成分表条目；查不到返回 None（调用方保留模型原值）。

    三级匹配，从严到宽：
      ① 精确：规范名或别名全等；
      ② 包含：先「表名 ⊆ 食材名」（长名优先），无果再反向兜底 —— 防短食材名
        误撞长菜名（番茄→番茄炒蛋）；
      ③ 相似度：difflib 兜底，阈值 0.85 防错行（「炒面」≠「炒饭」）。
    单字条目不参与包含匹配（「面」「虾」等子串误报率太高）。"""
    n = _norm(name)
    if not n:
        return None
    # ① 精确
    for e in FOODS:
        if n == _norm(e["n"]):
            return e
        for a in e["a"]:
            if n == _norm(a):
                return e
    # ② 包含，分两遍、各自长名优先：
    #    (a) 表名 ⊆ 食材名（可靠方向）：「牛肉片」→ 牛肉、「清炒土豆丝」→(别名)炒土豆丝；
    #    (b) 食材名 ⊆ 表名（兜底方向）：「炒蛋」→ 番茄炒蛋。方向 (b) 有「番茄→番茄炒蛋」
    #        式误配风险，只在前一遍全军覆没时启用 —— 而番茄/牛肉这类本身有词条的
    #        名字在 ① 已精确命中，永远走不到这里。
    for direction in ("subset", "super"):
        ranked = sorted(FOODS, key=lambda e: -len(_norm(e["n"])))
        for e in ranked:
            en = _norm(e["n"])
            if len(en) >= 2:
                hit = (en in n) if direction == "subset" else (n in en)
                if hit:
                    return e
            for a in e["a"]:
                an = _norm(a)
                if len(an) >= 2:
                    hit = (an in n) if direction == "subset" else (n in an)
                    if hit:
                        return e
    # ③ 相似度兜底
    import difflib
    pool = {}
    for e in FOODS:
        pool[_norm(e["n"])] = e
        for a in e["a"]:
            pool.setdefault(_norm(a), e)
    hit = difflib.get_close_matches(n, pool.keys(), n=1, cutoff=0.85)
    return pool[hit[0]] if hit else None
